# ============================================================
# TRAJETÓRIA CIRCULAR
# ============================================================

theta = np.linspace(0, 2*np.pi, 20)

raio = 1.0
xc = 1.0
yc = 0.0

trajetorias["Circular"] = np.column_stack((
    xc + raio*np.cos(theta),
    yc + raio*np.sin(theta)
))

# ============================================================
# PLOT
# ============================================================

n = len(trajetorias)

fig, axes = plt.subplots(
    nrows=5,
    ncols=3,
    figsize=(12, 18)
)

axes = axes.flatten()

for ax, (nome, pontos) in zip(axes, trajetorias.items()):

    x = pontos[:, 0]
    y = pontos[:, 1]

    ax.plot(x, y, '-o', linewidth=2, markersize=5)

    # ponto inicial
    ax.scatter(x[0], y[0], s=100, marker='s', label='Início')

    # ponto final
    ax.scatter(x[-1], y[-1], s=100, marker='x', label='Fim')

    ax.set_title(nome)
    ax.set_xlabel('x')
    ax.set_ylabel('y(x)')

    ax.grid(True)
    ax.axis('equal')
    ax.legend()

# remove subplot vazio
if len(axes) > n:
    for i in range(n, len(axes)):
        fig.delaxes(axes[i])